/* Pure model. Shared by Max v8 (include) and the dependency-free Node tests. */
var KLJModel = (function () {
    "use strict";
    var MODES = ["NOTE", "NOTE IN KEY", "PADS", "64 PADS"];
    var ROOTS = ["C", "C#", "D", "D#", "E", "F", "F#", "G", "G#", "A", "A#", "B"];
    // Names read from Live 12.4's native scale chooser (3 November 2026).
    var SCALES = ["Major", "Minor", "Dorian", "Mixolydian", "Lydian", "Phrygian", "Locrian",
        "Whole Tone", "Half-whole Dim.", "Whole-half Dim.", "Minor Blues", "Minor Pentatonic",
        "Major Pentatonic", "Harmonic Minor", "Harmonic Major", "Dorian #4", "Phrygian Dominant",
        "Melodic Minor", "Lydian Augmented", "Lydian Dominant", "Super Locrian", "8-Tone Spanish",
        "Bhairav", "Hungarian Minor", "Hirajoshi", "In-Sen", "Iwato", "Kumoi", "Pelog Selisir",
        "Pelog Tembung", "Messiaen 3", "Messiaen 4", "Messiaen 5", "Messiaen 6", "Messiaen 7"];
    function clone(x) { return JSON.parse(JSON.stringify(x)); }
    function normalizeName(value) { return String(value == null ? "" : value).trim(); }
    function empty() { return {version: 1, nextId: 1, tracks: [], rows: []}; }
    function key(s, prefix) { return prefix + s.nextId++; }
    function eligible(t) {
        return !!(t && t.id && t.midi && !t.audio && !t.group && !t.control);
    }
    function validate(s) {
        if (!s || s.version !== 1 || !Array.isArray(s.rows) || !Array.isArray(s.tracks))
            throw new Error("Invalid KLJ state or unsupported version");
        var trackKeys = new Set(), rowIds = new Set(), names = new Set();
        if (!Number.isSafeInteger(s.nextId) || s.nextId < 1) throw new Error("Invalid ID counter");
        s.tracks.forEach(function (t) {
            if (!t || typeof t.key !== "string" || !/^t\d+$/.test(t.key) || trackKeys.has(t.key) || typeof t.name !== "string")
                throw new Error("Invalid track reference");
            trackKeys.add(t.key);
        });
        s.rows.forEach(function (r) {
            if (!r || typeof r.id !== "string" || !/^r\d+$/.test(r.id) || rowIds.has(r.id)) throw new Error("Invalid row ID");
            rowIds.add(r.id);
            if (typeof r.clip !== "string" || !r.clip || r.clip !== normalizeName(r.clip) || names.has(r.clip))
                throw new Error("CLIP name is empty, untrimmed or duplicated");
            names.add(r.clip);
            if (!Number.isFinite(r.bpm) || r.bpm < 20 || r.bpm > 999) throw new Error("BPM must be between 20 and 999");
            if (!Number.isInteger(r.root) || r.root < 0 || r.root > 11 || typeof r.scale !== "string" || !r.scale.trim()) throw new Error("Invalid ROOT/SCALE");
            if (!MODES.includes(r.pushMode) || typeof r.script !== "string" || !r.enabled || typeof r.enabled !== "object" || Array.isArray(r.enabled))
                throw new Error("Invalid configuration");
            if (r.push !== null && !trackKeys.has(r.push)) throw new Error("Invalid Push reference");
            Object.keys(r.enabled).forEach(function (k) {
                if (!trackKeys.has(k) || (r.enabled[k] !== 0 && r.enabled[k] !== 1)) throw new Error("Invalid track state");
            });
            s.tracks.forEach(function (t) { if (!(t.key in r.enabled)) throw new Error("Incomplete configuration"); });
        });
        var ids = s.tracks.map(function (t) {return Number(t.key.slice(1));})
            .concat(s.rows.map(function (r) {return Number(r.id.slice(1));}));
        if (ids.some(function (n) {return n >= s.nextId;})) throw new Error("Inconsistent saved ID counter");
        return clone(s);
    }
    function migrate(saved) {
        // V1 may contain trailing whitespace generated by jit.cellblock's symbol output.
        // Keep every row and all its fields. Conflicting normalized names receive a visible suffix.
        var s = clone(saved), changes = [];
        if (!s || !Array.isArray(s.rows)) return {state: validate(s), changes: changes};
        var reserved = new Set(s.rows.map(function (r) {return normalizeName(r.clip);})), used = new Set();
        s.rows.forEach(function (r) {
            var raw = r.clip;
            if (typeof raw !== "string") throw new Error("Invalid CLIP name");
            var name = normalizeName(raw), base = name, n = 2;
            if (!name) throw new Error("A saved configuration has an empty name");
            if (used.has(name)) {
                do {name = base + "_" + n++;} while (used.has(name) || reserved.has(name));
            }
            used.add(name); r.clip = name;
            if (raw !== name) changes.push({id: r.id, raw: raw, rawLength: raw.length, name: name, length: name.length});
        });
        return {state: validate(s), changes: changes};
    }
    function reconcile(s, live, previous, initial, preserveUnresolved) {
        var tracks = live.filter(eligible), counts = Object.create(null), oldCounts = Object.create(null);
        tracks.forEach(function (t) { counts[t.name] = (counts[t.name] || 0) + 1; });
        s.tracks.forEach(function (t) { oldCounts[t.name] = (oldCounts[t.name] || 0) + 1; });
        var used = new Set(), runtime = [], saved = s.tracks.slice();
        var previousKeys = new Set((initial ? [] : previous || []).map(function (t) {return t.key;}));
        tracks.forEach(function (t) {
            var old = initial ? s.tracks.find(function (x) {
                return x.name === t.name && counts[t.name] === 1 && oldCounts[t.name] === 1;
            }) : (previous || []).find(function (x) { return x.id === t.id; });
            if (!old && preserveUnresolved) old = saved.find(function (x) {
                return !previousKeys.has(x.key) && !used.has(x.key) && x.name === t.name && counts[t.name] === 1 && oldCounts[t.name] === 1;
            });
            var k = old && !used.has(old.key) ? old.key : key(s, "t");
            used.add(k);
            runtime.push({key: k, id: t.id, name: t.name, position: t.position, ambiguous: counts[t.name] > 1});
        });
        s.tracks = runtime.map(function (t) {
            var record = clone(saved.find(function (x) {return x.key === t.key;}) || {key: t.key});
            record.name = t.name; return record;
        });
        if (preserveUnresolved) saved.forEach(function (t) {
            if (!used.has(t.key) && !previousKeys.has(t.key)) {s.tracks.push(t); used.add(t.key);}
        });
        s.rows.forEach(function (r) {
            Object.keys(r.enabled).forEach(function (k) {if (!used.has(k)) delete r.enabled[k];});
            s.tracks.forEach(function (t) {if (!(t.key in r.enabled)) r.enabled[t.key] = 0;});
            if (!used.has(r.push)) r.push = null;
        });
        return runtime;
    }
    function uniqueName(s, base) {
        var result = base, n = 2;
        while (s.rows.some(function (r) {return r.clip === result;})) result = base + "_" + n++;
        return result;
    }
    function add(s, defaults, original) {
        var r = original ? clone(original) : {clip: "NEW_CLIP", bpm: defaults.bpm, root: defaults.root,
            scale: defaults.scale, enabled: {}, push: null, pushMode: "NOTE", script: ""};
        r.id = key(s, "r");
        r.clip = uniqueName(s, normalizeName(original ? original.clip : r.clip) + (original ? "_COPY" : ""));
        s.tracks.forEach(function (t) {if (!(t.key in r.enabled)) r.enabled[t.key] = 0;});
        s.rows.push(r);
        return r;
    }
    function parseKey(text) {
        var m = /^([A-Ga-g])([#b]?)\s+(.+)$/.exec(String(text).trim());
        if (!m) throw new Error("KEY: enter C Minor or F# Major, for example");
        var root = ROOTS.indexOf(m[1].toUpperCase());
        if (m[2] === "#") root = (root + 1) % 12;
        if (m[2] === "b") root = (root + 11) % 12;
        var scale = SCALES.find(function (s) {return s.toLowerCase() === m[3].toLowerCase();});
        if (!scale) throw new Error("Unknown scale: " + m[3]);
        return {root: root, scale: scale};
    }
    function Gate() { this.last = null; }
    Gate.prototype.read = function (snapshot, prime) {
        var id = snapshot && snapshot.playing ? snapshot.id : null;
        var launch = id !== null && id !== this.last;
        this.last = id;
        return !prime && launch ? snapshot : null;
    };
    function apply(row, runtime, io) {
        var warnings = [];
        function attempt(label, fn) {try {fn();} catch (e) {warnings.push(label + " : " + e.message);}}
        attempt("BPM", function () {io.song("tempo", row.bpm);});
        attempt("KEY", function () {io.song("root_note", row.root);});
        attempt("KEY", function () {io.song("scale_name", row.scale);});
        runtime.forEach(function (t) {
            attempt(t.name, function () {
                if (t.ambiguous) throw new Error("duplicate track name, command skipped");
                if (row.enabled[t.key] !== 0 && row.enabled[t.key] !== 1) throw new Error("missing state");
                io.mute(t, row.enabled[t.key] ? 0 : 1);
            });
        });
        if (row.push !== null) attempt("Push", function () {
            var t = runtime.find(function (t) {return t.key === row.push;});
            if (!t || t.ambiguous) throw new Error("track missing or ambiguous");
            io.select(t);
        });
        // The caller invokes the script only after this synchronous standard recall.
        return warnings;
    }
    return {MODES: MODES, ROOTS: ROOTS, SCALES: SCALES, clone: clone, empty: empty, validate: validate,
        normalizeName: normalizeName, migrate: migrate,
        eligible: eligible, reconcile: reconcile, add: add, parseKey: parseKey, Gate: Gate, apply: apply};
}());
if (typeof module !== "undefined" && module.exports) module.exports = KLJModel;
